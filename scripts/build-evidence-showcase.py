"""Refresh the website's network panel. Historical test exhibits stay local."""
import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def network_panel():
    config = json.loads((ROOT / 'upgrade/config.json').read_text())
    address = config['registryAddress']
    assert re.fullmatch(r'0x[0-9a-fA-F]{40}', address)
    assert config['mode'] == 'testnet' and config['chainId'] == 11155111
    return f'''<div class="section-heading section-head"><div><h2>网络信息</h2><p>查看工作台使用的网络与合约。</p></div></div>
<article class="network-card panel"><dl class="network-summary">
<div><dt>网络</dt><dd id="network-name">Sepolia 测试网</dd></div>
<div><dt>链 ID</dt><dd id="network-chain">11155111</dd></div>
<div class="network-contract"><dt>合约地址</dt><dd><code id="network-address">{escape(address)}</code></dd></div>
</dl><a id="network-explorer" class="network-explorer" href="https://sepolia.etherscan.io/address/{escape(address)}" target="_blank" rel="noopener noreferrer">在区块浏览器查看合约 ↗</a></article>'''


def replace_section(path, section_id, attributes):
    source = path.read_text()
    markup = f'<section {attributes}>\n<!-- NETWORK_INFO_START: generated by scripts/build-evidence-showcase.py -->\n{network_panel()}\n<!-- NETWORK_INFO_END -->\n</section>'
    pattern = r'<section\b[^>]*\bid="' + section_id + r'"[^>]*>.*?</section>'
    source, count = re.subn(pattern, lambda _: markup, source, count=1, flags=re.S)
    assert count == 1, f'Missing panel: {section_id}'
    source = re.sub(r'<link\b[^>]*href="(?:\.\./)?evidence/showcase\.css[^>]*>', '', source)
    source = re.sub(r'<script\b[^>]*src="(?:\.\./)?evidence/showcase\.js[^>]*></script>', '', source)
    source = source.replace('06 · 上链记录', '06 · 网络信息').replace('<span>上链记录</span>', '<span>网络信息</span>')
    path.write_text(source)


if __name__ == '__main__':
    replace_section(ROOT / 'ProofPass_跨校证书核验实验室.html', 'demo-evidence', 'class="page" id="demo-evidence" aria-label="网络信息"')
    replace_section(ROOT / 'upgrade/index.html', 'evidence', 'id="evidence" class="panel" role="tabpanel" aria-labelledby="tab-evidence" hidden')
    print('Updated network panels; historical test screenshots and reports are not embedded.')
